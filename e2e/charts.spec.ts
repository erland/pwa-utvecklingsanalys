import {test,expect} from '@playwright/test';
import ExcelJS from 'exceljs';
test('chart modes reuse imported data and preserve accessible totals',async({page})=>{
 const wb=new ExcelJS.Workbook(),s=wb.addWorksheet('UO Tot 2027-30');
 s.getCell('B1').value='UO: UO A';s.getCell('D11').value=new Date(2027,0,1);
 s.getCell('B25').value='LO 1';s.getCell('C26').value='IT timmar (h)';s.getCell('D26').value=42;
 const buffer=Buffer.from(await wb.xlsx.writeBuffer());
 await page.goto('./');await page.getByRole('button',{name:'Import',exact:true}).click();
 await page.locator('#import-files').setInputFiles({name:'uo-a.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer});
 await page.getByRole('button',{name:'Godkänn import'}).click();
 await expect(page.getByRole('status')).toContainText('Importen godkänd');
 await page.getByRole('button',{name:'Analys',exact:true}).click();
 await expect(page.locator('.result-head strong')).toHaveText('42 h');
 await expect(page.locator('.analysis-table')).toContainText('42 h');
 await page.getByLabel('Visualisering',{exact:true}).selectOption('pie');
 await expect(page.getByRole('img',{name:/Cirkeldiagram, total 42 h/})).toBeVisible();
 await expect(page.locator('.pie-legend')).toContainText('100 %');
 await expect(page.locator('.analysis-table')).toContainText('42 h');
 await page.getByLabel('Visualisering',{exact:true}).selectOption('table');
 await expect(page.locator('.pie-chart')).toHaveCount(0);
 await expect(page.locator('.analysis-table')).toContainText('42 h');
 await page.getByLabel('Visualisering',{exact:true}).selectOption('bar');
 await expect(page.getByLabel('Stapeldiagram')).toBeVisible();
 await expect(page.locator('.analysis-table')).toContainText('42 h');
});
