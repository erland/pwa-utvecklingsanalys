import {test,expect} from '@playwright/test';
import ExcelJS from 'exceljs';

test('DEV-131 optional allocation is configured in Settings with LO override',async({page})=>{
 const workbook=new ExcelJS.Workbook(),sheet=workbook.addWorksheet('UO Tot 2027-30');
 sheet.getCell('B1').value='UO: Test UO';sheet.getCell('D11').value=2027;
 sheet.getCell('B25').value='LO A';sheet.getCell('C26').value='IT timmar (h)';sheet.getCell('D26').value=50;
 sheet.getCell('B29').value='LO B';sheet.getCell('C30').value='IT timmar (h)';sheet.getCell('D30').value=30;
 await page.addInitScript(()=>localStorage.removeItem('utvecklingsanalys:e2e-legacy-navigation'));
 await page.goto('./');
 await page.getByRole('button',{name:'Import',exact:true}).click();
 await page.locator('#direct-import-files').setInputFiles({name:'optional-allocation.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(await workbook.xlsx.writeBuffer())});
 await expect(page.getByRole('status')).toContainText('importerad');
 await page.getByRole('button',{name:'Analys',exact:true}).click();
 await expect(page.getByRole('region',{name:'Fördelningsanalys'})).toBeVisible();
 await page.getByRole('button',{name:'Inställningar'}).click();
 const view=page.getByRole('region',{name:'Valfria fördelningstyper'});
 await expect(view).toBeVisible();
 await expect(view.getByLabel('Namn på fördelningstyp')).toHaveCount(0);
 await view.getByRole('button',{name:'Ny fördelningstyp'}).click();
 await view.getByLabel('Namn på fördelningstyp').fill('Effekt');
 await view.getByLabel('Kategori 1',{exact:true}).fill('Förutsättningsskapande');
 await view.getByLabel('Kategori 2',{exact:true}).fill('Direkt effekt');
 await view.getByRole('button',{name:'Skapa fördelningstyp'}).click();
 await expect(view.getByRole('status')).toContainText('Fördelningen sparades');
 await page.getByRole('button',{name:'Fördelningar',exact:true}).click();
 const rules=page.getByRole('region',{name:'Valfria fördelningar'});
 await expect(rules).toBeVisible();
 await rules.getByRole('region',{name:'Översikt fördelningstyper'}).getByRole('button',{name:/Effekt/}).click();
 await expect(rules.getByRole('heading',{name:'Effekt – Fördela per UO och LO'})).toBeVisible();
 const uoOverview=rules.getByRole('region',{name:'Översikt UO-fördelningar'});
 await expect(uoOverview).toBeVisible();
 await expect(rules.getByRole('region',{name:'Timviktad fördelning Test UO'})).toHaveCount(0);
 await uoOverview.getByRole('button',{name:/Test UO.*LO/}).click();
 const editor=rules.getByRole('region',{name:'Timviktad fördelning Test UO'});
 await expect(editor).toBeVisible();
 const uoSlider=editor.getByRole('slider',{name:'UO Test UO – Fördelningsreglage'});
 await uoSlider.focus();await uoSlider.press('End');
 await expect(uoSlider).toHaveValue('100');
 await expect(rules.getByRole('status').filter({hasText:'Fördelningen sparades'})).toBeVisible();
 await expect(editor.getByRole('button',{name:'Spara fördelning för Test UO'})).toHaveCount(0);
 await editor.getByRole('button',{name:/Test UO.*Visa LO/}).click();
 const loSlider=editor.getByRole('slider',{name:'LO A – Fördelningsreglage'});
 await loSlider.focus();await loSlider.press('Home');
 await expect(loSlider).toHaveValue('0');
 await expect(uoSlider).toHaveValue('37.5');
 await expect(editor.getByRole('status').filter({hasText:'Sparar fördelningen'})).toHaveCount(0);
 await expect(editor.getByRole('button',{name:'Spara fördelning för Test UO'})).toHaveCount(0);
 await page.getByRole('button',{name:'Analys',exact:true}).click();
 const allocation=page.getByRole('region',{name:'Fördelningsanalys'});
 await expect(allocation.getByLabel('Analysera fördelningstyp')).toHaveValue('resources');
 await allocation.getByLabel('Analysera fördelningstyp').selectOption({label:'Utveckling / Förvaltning'});
 await allocation.getByLabel('Analysera fördelningstyp').selectOption({label:'Effekt'});
 await expect(allocation).toBeVisible();
 await expect(allocation.getByRole('table',{name:'Fördelning Effekt'})).toBeVisible();
 await expect(allocation.getByRole('rowheader',{name:'Förutsättningsskapande'})).toBeVisible();
 await expect(allocation.getByRole('rowheader',{name:'Direkt effekt'})).toBeVisible();
 await expect(allocation.getByLabel('Presentera fördelning')).toHaveCount(0);
 await expect(allocation.getByRole('img')).toHaveCount(1);
 await page.getByRole('combobox',{name:'enhet'}).selectOption('costs');
 await expect(page.getByRole('region',{name:'Fördelningsanalys'})).toHaveCount(0);
 await page.getByRole('combobox',{name:'enhet'}).selectOption('hours');
 await expect(allocation).toBeVisible();
 await allocation.getByLabel('Analysera fördelningstyp').selectOption({label:'Effekt'});
 await page.getByRole('button',{name:'Fördelningar',exact:true}).click();
 const reopened=page.getByRole('region',{name:'Valfria fördelningar'});
 await reopened.getByRole('region',{name:'Översikt UO-fördelningar'}).getByRole('button',{name:/Test UO.*LO/}).click();
 const persisted=reopened.getByRole('region',{name:'Timviktad fördelning Test UO'});
 await persisted.getByRole('button',{name:/Test UO.*Visa LO/}).click();
 await expect(persisted.getByRole('slider',{name:'LO A – Fördelningsreglage'})).toHaveValue('0');
 await expect(persisted.getByRole('slider',{name:'UO Test UO – Fördelningsreglage'})).toHaveValue('37.5');
});
