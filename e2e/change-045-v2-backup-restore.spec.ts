import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';
import ExcelJS from 'exceljs';

test('CHANGE-045: approved v2 allocation survives real backup and restore in a fresh browser context',async({browser})=>{
 const source=await browser.newContext({acceptDownloads:true});
 const first=await source.newPage();
 const wb=new ExcelJS.Workbook(),sheet=wb.addWorksheet('UO Tot 2027-30');
 sheet.getCell('B1').value='UO: UO A';
 sheet.getCell('D11').value=2027;
 sheet.getCell('B25').value='LO 1';
 sheet.getCell('C26').value='IT timmar (h)';
 sheet.getCell('D26').value=42;
 sheet.getCell('D4').value='Utv. 27';
 sheet.getCell('E4').value='Förv. 27';
 sheet.getCell('C5').value='IT timmar (th)';
 sheet.getCell('D5').value=0.025;
 sheet.getCell('E5').value=0.017;
 const buffer=Buffer.from(await wb.xlsx.writeBuffer());
 await first.goto('./');
 await first.getByRole('button',{name:'Import',exact:true}).click();
 await first.locator('#direct-import-files').setInputFiles({name:'v2-backup.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer});
 await expect(first.getByRole('status')).toContainText('importerad');
 await first.getByRole('button',{name:'Kompletteringar',exact:true}).click();
 const allocation=first.getByRole('heading',{name:'Aktivitetsfördelning till LO'}).locator('..');
 await allocation.getByRole('button',{name:'Skapa fördelning'}).click();
 await expect(allocation.getByText('Inväntar godkännande')).toBeVisible();
 await allocation.getByLabel('godkännandemotivering',{exact:false}).fill('Godkänt inför projektbackup');
 await allocation.getByRole('button',{name:'Godkänn fördelning'}).click();
 await expect(allocation.getByText('Godkänd',{exact:true})).toBeVisible();
 await first.getByRole('button',{name:'Analys',exact:true}).click();
 const original=first.locator('.canonical-analytics');
 await expect(original.locator('.canonical-result-head strong')).toContainText('42 h');
 await original.getByLabel('aktivitet').selectOption('development');
 await expect(original.locator('.canonical-result-head strong')).toContainText('25 h');
 await first.getByRole('button',{name:'Inställningar',exact:true}).click();
 const downloadPromise=first.waitForEvent('download');
 await first.getByRole('button',{name:'Ladda ner projektbackup'}).click();
 const download=await downloadPromise;
 const bytes=await readFile(await download.path());
 const backup=JSON.parse(bytes.toString('utf8'));
 expect(backup.version).toBe(3);
 expect(backup.canonical.records.length).toBeGreaterThan(0);
 expect(backup.gapState.activityAllocationRules).toHaveLength(1);
 expect(backup.gapState.activityAllocationDecisions).toHaveLength(1);
 await source.close();

 const target=await browser.newContext({acceptDownloads:true});
 const second=await target.newPage();
 await second.goto('./');
 await second.getByRole('button',{name:'Inställningar',exact:true}).click();
 await second.getByLabel('Välj projektbackup').setInputFiles({name:'v2-backup.json',mimeType:'application/json',buffer:bytes});
 await expect(second.getByRole('status')).toContainText('Validerad backup');
 await second.getByRole('button',{name:'Bekräfta återställning'}).click();
 await expect(second.getByRole('status')).toContainText('Projekt återställt');
 await second.reload();
 await second.getByRole('button',{name:'Analys',exact:true}).click();
 const restored=second.locator('.canonical-analytics');
 await expect(restored.locator('.canonical-result-head strong')).toContainText('42 h');
 await restored.getByLabel('aktivitet').selectOption('development');
 await expect(restored.locator('.canonical-result-head strong')).toContainText('25 h');
 await restored.getByLabel('aktivitet').selectOption('maintenance');
 await expect(restored.locator('.canonical-result-head strong')).toContainText('17 h');
 await second.getByRole('button',{name:'Kompletteringar',exact:true}).click();
 await expect(second.getByRole('heading',{name:'Aktivitetsfördelning till LO'}).locator('..').getByText('Godkänd',{exact:true})).toBeVisible();
 await target.close();
});
