import {test,expect} from '@playwright/test';
import ExcelJS from 'exceljs';
test('portrait tablet shows full-width analysis and collapsible filters',async({page})=>{
 await page.setViewportSize({width:820,height:1180});
 const book=new ExcelJS.Workbook(),s=book.addWorksheet('UO Tot 2027-30');
 s.getCell('B1').value='UO: UO A';s.getCell('D11').value=new Date(2027,0,1);
 s.getCell('B25').value='LO AUL';s.getCell('C26').value='IT timmar (h)';s.getCell('D26').value=42;
 const bytes=Buffer.from(await book.xlsx.writeBuffer());
 await page.goto('./');
 const sidebar=page.locator('.sidebar'),content=page.locator('.content');
 const bounds=await Promise.all([sidebar.boundingBox(),content.boundingBox()]);
 expect(bounds[0]?.width).toBeGreaterThan(790);
 expect(bounds[1]?.width).toBeGreaterThan(790);
 await expect(page.getByText('Konfigurera',{exact:true})).toBeVisible();
 await expect(page.getByText('Komplettera',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Import',exact:true}).click();
 await page.locator('#import-files').setInputFiles({name:'test.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:bytes});
 await page.getByRole('button',{name:'Godkänn import'}).click();
 await expect(page.getByRole('status')).toContainText('Importen godkänd');
 await page.getByRole('button',{name:'Analys',exact:true}).click();
 const v2=page.locator('.canonical-analytics');
 await expect(v2).toBeVisible();
 await expect(v2.locator('.canonical-result-head strong')).toContainText('42 h');
 const box=await v2.boundingBox();
 expect(box?.width).toBeGreaterThan(740);
});
