import {test,expect} from '@playwright/test';
import ExcelJS from 'exceljs';
test('approve LO allocation and compare with source without double counting',async({page})=>{
 const book=new ExcelJS.Workbook(),s=book.addWorksheet('UO Tot 2027-30');
 s.getCell('B1').value='UO: UO A';s.getCell('D11').value=new Date(2027,0,1);
 s.getCell('B25').value='LO AUL';s.getCell('C26').value='IT timmar (h)';s.getCell('D26').value=20;
 s.getCell('B31').value='LO IA';s.getCell('C32').value='IT timmar (h)';s.getCell('D32').value=30;
 s.getCell('D4').value='Utv. 27';s.getCell('C5').value='IT timmar (th)';s.getCell('D5').value=1;
 const bytes=Buffer.from(await book.xlsx.writeBuffer());
 await page.goto('./');await page.getByRole('button',{name:'Import',exact:true}).click();
 await page.locator('#direct-import-files').setInputFiles({name:'allocation.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:bytes});
 await expect(page.getByRole('status')).toContainText('importerad');
 await page.getByRole('button',{name:'Kompletteringar'}).click();
 await page.getByLabel('Kravnamn').fill('LO-utveckling');
 await page.getByLabel('Aktiviteter').fill('development');
 await page.getByRole('button',{name:'Lägg till informationskrav'}).click();
 await page.getByLabel('Fördelningsmotivering').fill('Proportionellt efter detaljtimmar');
 await page.getByRole('button',{name:'Skapa och kontrollera fördelningsregel'}).click();
 await expect(page.getByTestId('distribution-total')).toContainText('1 000');
 await page.getByRole('button',{name:'Godkänn fördelning'}).click();
 await expect(page.getByText('Godkänd och aktuell')).toBeVisible();
 await page.getByRole('button',{name:'Analys',exact:true}).click();
 await expect(page.locator('.canonical-analytics .canonical-result-head strong')).toContainText('50 h');
});
